DEFINE DYNAMIC TABLE SALES_CICD{{env}}.ANALYTICS.DT_DAILY_SALES
    TARGET_LAG = '{{target_lag}}'
    WAREHOUSE = SALES_CICD_WH{{env}}
    COMMENT = 'Daily revenue and order counts'
AS
SELECT
    DATE(ORDER_TS) AS SALE_DATE,
    SUM(AMOUNT) AS REVENUE,
    COUNT(*) AS ORDERS,
    SALES_REGION,    
FROM SALES_CICD{{env}}.RAW.ORDERS
GROUP BY 1,4;

DEFINE PROCEDURE SALES_CICD{{env}}.APPS.SP_LOAD_ORDERS(NUM_ROWS NUMBER)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Generates sample orders for the demo'
AS
$$
BEGIN
    INSERT INTO SALES_CICD{{env}}.RAW.ORDERS (ORDER_ID, CUSTOMER_ID, AMOUNT, ORDER_TS,SALES_REGION)
    SELECT
        UNIFORM(1, 1000000000, RANDOM()),
        UNIFORM(1, 100, RANDOM()),
        UNIFORM(1000, 50000, RANDOM()) / 100,
        DATEADD('minute', -UNIFORM(0, 43200, RANDOM()), CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
        ARRAY_CONSTRUCT('NA','EMEA','APAC')[UNIFORM(0,2,RANDOM())]::VARCHAR
    FROM TABLE(GENERATOR(ROWCOUNT => :NUM_ROWS));
    RETURN 'Loaded ' || SQLROWCOUNT || ' orders';
END;
$$;
